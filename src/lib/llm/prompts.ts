export function buildContextPrompt(evidence: any[]): string {
  if (!evidence || evidence.length === 0) return "اطلاعاتی یافت نشد.";

  const contextParts = evidence.map((e, index) => {
    const sectionInfo = e.section ? ` - بخش: ${e.section}` : '';
    return `[منبع ${index + 1}: ${e.title}${sectionInfo}]\n${e.content}`;
  });

  return `--- اطلاعات مستندات لیارا ---\n${contextParts.join('\n\n')}\n-----------------------------`;
}
